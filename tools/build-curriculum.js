// node tools/build-curriculum.js — splits curriculum/src.js into a browser file (no answers) and a server answer key.
const fs = require("fs"), path = require("path");
const src = require("../curriculum/src.js");
const pub = {}, key = {};
for (const [id, c] of Object.entries(src)) {
  for (const u of c.units) {
    if (!u.qs || u.qs.length < 2) throw new Error("need >=2 questions: " + id + " / " + u.t);
    for (const q of u.qs) if (!(q.a >= 0 && q.a < q.o.length)) throw new Error("bad answer index in " + id + " / " + u.t);
  }
  const strip = ({ qs, ...rest }) => ({ ...rest, qs: qs.map((q) => ({ p: q.p, o: q.o })) });
  pub[id] = { outcome: c.outcome, lab: c.lab, units: c.units.map(strip) };
  key[id] = c.units.map((u) => u.qs.map((q) => q.a));
}
fs.writeFileSync(path.join(__dirname, "../dist/academy-curriculum.js"),
  "/* generated by tools/build-curriculum.js — lessons, checkpoint questions and labs (answers are graded on the server) */\n(function (g) { g.DBA_CUR = " + JSON.stringify(pub) + "; })(typeof globalThis !== 'undefined' ? globalThis : window);\n");
fs.writeFileSync(path.join(__dirname, "../api/_academy_answers.js"),
  "// generated by tools/build-curriculum.js — server-only answer key (per unit: one index per question)\nmodule.exports = " + JSON.stringify(key) + ";\n");
const words = Object.values(pub).reduce((n, c) => n + c.units.reduce((m, u) => m + JSON.stringify(u.body).split(" ").length, 0), 0);
console.log("courses:", Object.keys(pub).length, "units:", Object.values(pub).reduce((n, c) => n + c.units.length, 0), "body words:", words);
